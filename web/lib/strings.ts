function merge(base: Dict, ...extras: Dict[]): Dict {
  const out: Dict = { ...base };
  for (const extra of extras) {
    for (const [k, v] of Object.entries(extra)) {
      const cur = out[k];
      out[k] = typeof v === "object" && typeof cur === "object" ? merge(cur, v) : v;
    }
  }
  return out;
}

